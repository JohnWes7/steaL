package io.github.johnwes7.steal.views.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import io.github.johnwes7.steal.R

/**
 * App 的字体样式，目前全用 Material 3 默认值（字体是手机的系统字体）。
 * The app's text styles, currently all Material 3 defaults (in the phone's system font).
 *
 * 默认样式以 sp 为单位，会跟着系统字体大小缩放；要改某个样式时在这里覆盖，不在页面里写死字号。
 * The defaults are in sp and scale with the system font size; override a style here when needed
 * rather than hard-coding sizes in screens.
 */
internal val AppTypography = Typography()

/**
 * 品牌字标用的字体：打包在 App 里的 Roboto Bold，不跟手机的系统字体变。
 * The brand wordmark font: Roboto Bold bundled with the app, unaffected by the phone's system font.
 *
 * 只打包了 Bold 一个字重，要别的粗细也会显示成 Bold。
 * Only the Bold weight is bundled, so other weights also render as Bold.
 */
internal val BrandFontFamily = FontFamily(Font(R.font.roboto_bold, FontWeight.Bold))

/**
 * 品牌头部里中文文字用的字体：打包在 App 里的 Noto Sans SC Bold，不跟手机的系统字体变。
 * The font for Chinese text in the brand header: Noto Sans SC Bold bundled with the app, unaffected by the phone's
 * system font.
 *
 * 只含中文翻译文件里用到的字（`tools/brand-font/` 生成），没有的字由系统字体显示。
 * It only contains the characters used in the Chinese translation file (generated by `tools/brand-font/`); missing
 * characters are drawn with the system font.
 */
internal val BrandHanFontFamily = FontFamily(Font(R.font.noto_sans_sc_bold, FontWeight.Bold))

/**
 * 品牌头部里 [text] 该用的字体：含汉字用 [BrandHanFontFamily]，否则用 [BrandFontFamily]。
 * The brand header font for [text]: [BrandHanFontFamily] when it contains Chinese characters, [BrandFontFamily]
 * otherwise.
 *
 * Compose 的 `FontFamily` 按粗细挑字体、不会按「有没有这个字」换字体，Roboto 没有的汉字会落到系统字体，所以按文字选。
 * A Compose `FontFamily` picks fonts by weight, not by whether they have a glyph, so Chinese characters missing from
 * Roboto would fall to the system font; hence the choice by text.
 */
internal fun brandFontFamilyFor(text: String): FontFamily {
    val containsHan = text.codePoints().anyMatch { codePoint ->
        Character.UnicodeScript.of(codePoint) == Character.UnicodeScript.HAN
    }
    if (containsHan) {
        return BrandHanFontFamily
    }
    return BrandFontFamily
}
